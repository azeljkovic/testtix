/**
 * Builds `dark-palette.css`, the dark theme of Tailwind's colour palette (see that file).
 * `dark-palette.test.ts` runs it and compares the result with the committed file.
 *
 * Each dark colour keeps the WCAG contrast its light colour has against white, measured against
 * the dark page colour (`white` in the dark theme) instead: `text-slate-600` on `bg-white` reads
 * 7.56:1 in both themes, and a step close to white (`slate-50`, `amber-100`) stays close to the
 * page. The hue comes from the step itself and the chroma from its mirror step (50 ↔ 950), so tinted
 * backgrounds stay tinted and light text stays light; colours outside sRGB lose chroma until they
 * fit.
 */

export const PALETTE_STEPS = [
  '50',
  '100',
  '200',
  '300',
  '400',
  '500',
  '600',
  '700',
  '800',
  '900',
  '950',
] as const;

/** The dark theme's page colour, which `white` becomes. */
const DARK_SURFACE: Oklch = { l: 0.18, c: 0.03, h: 265 };

interface Oklch {
  l: number;
  c: number;
  h: number;
}

/** Hues with a full palette in Tailwind's `theme.css` (`red`, `slate`, …), in its order. */
export function paletteHues(themeCss: string): string[] {
  return [...themeCss.matchAll(/--color-([a-z]+)-500:/g)].map((match) => match[1] ?? '');
}

/** The palette hues that `source` (the app's code) uses in a utility class, e.g. `bg-amber-50`. */
export function usedHues(themeCss: string, source: string): string[] {
  return paletteHues(themeCss).filter((hue) =>
    new RegExp(`-${hue}-(${PALETTE_STEPS.join('|')})\\b`).test(source),
  );
}

export function darkPaletteCss(themeCss: string, hues: readonly string[]): string {
  const surface = clipToSrgb(DARK_SURFACE);
  const surfaceLuminance = luminance(surface);
  const declarations = [`--color-white: light-dark(#fff, ${format(surface)});`];

  for (const hue of hues) {
    PALETTE_STEPS.forEach((step, index) => {
      const name = `${hue}-${step}`;
      const light = themeColor(themeCss, name);
      const mirror = themeColor(
        themeCss,
        `${hue}-${PALETTE_STEPS[PALETTE_STEPS.length - 1 - index] ?? step}`,
      );
      const contrast = (1 + 0.05) / (luminance(light) + 0.05);
      const dark = withLuminance(
        { l: 0, c: mirror.c, h: light.h },
        contrast * (surfaceLuminance + 0.05) - 0.05,
      );
      // Tailwind's own value as written, so the light theme doesn't change at all.
      declarations.push(`--color-${name}: light-dark(${light.css}, ${format(dark)});`);
    });
  }

  return `${HEADER}
@layer base {
  :root {
${declarations.map((line) => `    ${line}`).join('\n')}
  }
}
`;
}

const HEADER = `/*
 * Generated by src/theme/dark-palette.test.ts from Tailwind's palette (rules in dark-palette.ts).
 * Don't edit: after a Tailwind update or a class with a new hue, run
 * \`pnpm --filter @testtix/web test -u src/theme\` and commit the result.
 *
 * Every palette colour the app uses is \`light-dark(<Tailwind's colour>, <dark colour>)\`, so the
 * light-mode classes (\`bg-white\`, \`text-slate-600\`, \`bg-amber-50\`) also make the dark theme.
 */`;

function themeColor(themeCss: string, name: string): Oklch & { css: string } {
  const match = new RegExp(`--color-${name}: (oklch\\(([\\d.]+)% ([\\d.]+) ([\\d.]+)\\))`).exec(
    themeCss,
  );
  if (!match) throw new Error(`Tailwind's theme has no --color-${name}`);
  return {
    css: match[1] ?? '',
    l: Number(match[2]) / 100,
    c: Number(match[3]),
    h: Number(match[4]),
  };
}

/** `color` with the lightness (found by bisection) that gives it `target` relative luminance. */
function withLuminance(color: Oklch, target: number): Oklch {
  let low = 0;
  let high = 1;
  let result = clipToSrgb(color);
  for (let i = 0; i < 50; i++) {
    const l = (low + high) / 2;
    result = clipToSrgb({ ...color, l });
    if (luminance(result) < target) low = l;
    else high = l;
  }
  return result;
}

function clipToSrgb(color: Oklch): Oklch {
  if (inSrgb(color)) return color;
  let low = 0;
  let high = color.c;
  for (let i = 0; i < 40; i++) {
    const c = (low + high) / 2;
    if (inSrgb({ ...color, c })) low = c;
    else high = c;
  }
  return { ...color, c: low };
}

function inSrgb(color: Oklch): boolean {
  return linearSrgb(color).every((channel) => channel >= -1e-4 && channel <= 1 + 1e-4);
}

/** WCAG relative luminance. */
function luminance(color: Oklch): number {
  const [r, g, b] = linearSrgb(color).map((channel) => Math.min(1, Math.max(0, channel)));
  return 0.2126 * (r ?? 0) + 0.7152 * (g ?? 0) + 0.0722 * (b ?? 0);
}

/** OKLCH → linear sRGB (Björn Ottosson's OKLab matrices). */
function linearSrgb({ l, c, h }: Oklch): [number, number, number] {
  const a = c * Math.cos((h * Math.PI) / 180);
  const b = c * Math.sin((h * Math.PI) / 180);
  const lms = [
    (l + 0.3963377774 * a + 0.2158037573 * b) ** 3,
    (l - 0.1055613458 * a - 0.0638541728 * b) ** 3,
    (l - 0.0894841775 * a - 1.291485548 * b) ** 3,
  ] as const;
  return [
    4.0767416621 * lms[0] - 3.3077115913 * lms[1] + 0.2309699292 * lms[2],
    -1.2684380046 * lms[0] + 2.6097574011 * lms[1] - 0.3413193965 * lms[2],
    -0.0041960863 * lms[0] - 0.7034186147 * lms[1] + 1.707614701 * lms[2],
  ];
}

/** Rounded, without trailing zeros (as Prettier writes numbers, so `pnpm format` keeps the file). */
function format({ l, c, h }: Oklch): string {
  const round = (value: number, digits: number) => Number(value.toFixed(digits));
  return `oklch(${round(l * 100, 1)}% ${round(c, 3)} ${round(h, 1)})`;
}
