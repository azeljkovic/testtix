import { en, Faker } from '@faker-js/faker';

import type { BatchSpec, DayTime, EventSpec, VenueSlug } from './fixtures.js';

/** Faker's seed. Changing it (or upgrading Faker) changes the generated events. */
export const SEED_FAKER_SEED = 20261121;

/** How many events the seed generates on top of the named fixtures. */
export const GENERATED_EVENT_COUNT = 36;

const START_TIMES = ['23:00', '23:30', '00:00'] as const;

// Curated, so generated band names read like band names (Faker's own word lists are too random).
const BAND_ADJECTIVES = [
  'Velvet',
  'Neon',
  'Golden',
  'Electric',
  'Crimson',
  'Lunar',
  'Northern',
  'Paper',
  'Glass',
  'Hollow',
  'Silver',
  'Wild',
  'Quiet',
  'Copper',
  'Midnight',
  'Static',
  'Amber',
  'Distant',
] as const;
const BAND_NOUNS = [
  'Harbors',
  'Lanterns',
  'Foxes',
  'Tides',
  'Engines',
  'Pilots',
  'Sparrows',
  'Circuits',
  'Kites',
  'Comets',
  'Rivers',
  'Owls',
  'Satellites',
  'Parades',
  'Mirrors',
  'Lighthouses',
  'Wolves',
] as const;

/**
 * Filler events for the catalogue (pagination, filters, search), generated by Faker with a fixed
 * seed: the same list on every run. All are published and on sale, 1–90 days after the seed day.
 * Names are made up, never real artists.
 */
export function generateEventSpecs(count = GENERATED_EVENT_COUNT): EventSpec[] {
  const faker = new Faker({ locale: [en] });
  faker.seed(SEED_FAKER_SEED);
  const onSale: DayTime = [-14, '15:00'];

  return Array.from({ length: count }, (_, index): EventSpec => {
    const number = index + 1;
    const category = faker.helpers.arrayElement(['CONCERT', 'TALK', 'MEETUP'] as const);
    const starts: DayTime = [
      faker.number.int({ min: 1, max: 90 }),
      faker.helpers.arrayElement(START_TIMES),
    ];
    const common = { status: 'PUBLISHED', starts, salesOpen: onSale } as const;
    // The number keeps slugs unique even if Faker repeats a title.
    const slug = (title: string) => slugify(`${title} ${number}`);
    const price = (min: number, max: number) => faker.number.int({ min, max }) * 100;
    const batch = (name: string, sections: string[], priceCents: number): BatchSpec => ({
      name,
      priceCents,
      sections,
      releases: onSale,
    });

    switch (category) {
      case 'CONCERT': {
        const performer = `The ${faker.helpers.arrayElement(BAND_ADJECTIVES)} ${faker.helpers.arrayElement(BAND_NOUNS)}`;
        const venue: VenueSlug = faker.helpers.arrayElement(['riverside-hall', 'the-warehouse']);
        const title = `${performer} Live`;
        return {
          ...common,
          slug: slug(title),
          title,
          performer,
          description: faker.lorem.sentences(2),
          category,
          venue,
          durationMin: 150,
          batches:
            venue === 'riverside-hall'
              ? [
                  batch('Stalls', ['Stalls'], price(40, 120)),
                  batch('Balcony', ['Balcony'], price(20, 39)),
                ]
              : [
                  batch('Standing', ['Standing Floor'], price(20, 60)),
                  batch('Mezzanine', ['Mezzanine'], price(61, 90)),
                ],
        };
      }
      case 'TALK': {
        const performer = `${faker.person.firstName()} ${faker.person.lastName()}`;
        const title = titleCase(faker.company.buzzPhrase());
        return {
          ...common,
          slug: slug(title),
          title,
          performer,
          description: faker.lorem.sentences(2),
          category,
          venue: 'harbor-auditorium',
          durationMin: 90,
          batches: [batch('General', ['Main Floor'], price(10, 40))],
        };
      }
      case 'MEETUP': {
        const topic = `${titleCase(faker.hacker.adjective())} ${titleCase(faker.hacker.noun())}`;
        const title = `${topic} Meetup`;
        return {
          ...common,
          slug: slug(title),
          title,
          performer: `Port Ellis ${topic} Group`,
          description: faker.lorem.sentences(2),
          category,
          venue: 'loft-23',
          durationMin: 120,
          batches: [batch('Entry', ['Loft'], price(5, 20))],
        };
      }
    }
  });
}

function titleCase(text: string): string {
  return text.replace(
    /(^|[\s-])(\p{L})/gu,
    (_, sep: string, letter: string) => `${sep}${letter.toUpperCase()}`,
  );
}

/** `"Velvet Harbor in Concert 3"` → `"velvet-harbor-in-concert-3"`. */
export function slugify(text: string): string {
  return text
    .normalize('NFKD')
    .replace(/\p{Diacritic}/gu, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}
